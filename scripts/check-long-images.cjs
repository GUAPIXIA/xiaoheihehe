async page => {
  const states = { 'heybox.preferences': { theme: 'light', zoom: 100, shortcuts: true, animations: false, showSidebar: false }, 'heybox.community-filter': { mode: 'all', included: [], excluded: [], unknown: true } };
  const post = { id: 1, userId: 'test', author: '图片测试', avatar: '图', avatarUrl: '', color: '#789', time: '刚刚', title: '长图阅读验证', excerpt: '长图、横图与加载失败', body: [], topicIds: [], topics: [], likes: 0, comments: 0, images: ['/test-long.svg', '/test-wide.svg', '/test-error.svg'], level: 0, medalUrl: '', medalName: '', liked: false, createdAt: 0, videoUrl: '', isCy: false };
  let failed = true;
  await page.setViewportSize({ width: 900, height: 1000 });
  await page.addInitScript(saved => { for (const [key, value] of Object.entries(saved)) localStorage.setItem(key, JSON.stringify(value)); }, states);
  await page.route('**/test-*.svg', async route => {
    const url = route.request().url();
    if (url.includes('error') && failed) { await route.fulfill({ status: 404, body: '' }); return; }
    const height = url.includes('long') ? 8000 : 800;
    const rows = Array.from({ length: Math.ceil(height / 160) }, (_, i) => `<rect x="40" y="${i * 160 + 20}" width="1000" height="120" rx="12" fill="${i % 2 ? '#eef3f8' : '#f4f5f6'}"/><text x="70" y="${i * 160 + 90}" font-size="36" fill="#25272b">Reading line ${i + 1}</text>`).join('');
    await route.fulfill({ contentType: 'image/svg+xml', body: `<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="${height}"><rect width="100%" height="100%" fill="white"/>${rows}</svg>` });
  });
  await page.route('**/api/command', async route => {
    const request = route.request().postDataJSON();
    let data = null;
    switch (request.type) {
      case 'bootstrap': data = { account: null, states, dataDirectory: 'synthetic-test' }; break;
      case 'stateGet': data = states[request.payload.key] ?? null; break;
      case 'stateSet': states[request.payload.key] = request.payload.value; data = true; break;
      case 'communities': data = []; break;
      case 'emojis': data = { version: 'synthetic', emojis: [] }; break;
      case 'feed': data = { posts: [post], cursor: { offset: 1, topics: {}, exhausted: [], rotation: 0 }, hasMore: false }; break;
    }
    await route.fulfill({ json: { ok: true, data } });
  });
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('button', { name: '查看 长图阅读验证 的图片 1', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const view = dialog.locator('.gallery-viewport');
  const mode = name => dialog.getByRole('button', { name, exact: true });
  await page.waitForFunction(() => document.querySelector('.gallery-viewport')?.getAttribute('aria-busy') === 'false');
  const read = () => view.evaluate(el => ({ width: el.clientWidth, height: el.clientHeight, scrollHeight: el.scrollHeight, scrollWidth: el.scrollWidth, top: el.scrollTop, imageWidth: el.querySelector('img')?.getBoundingClientRect().width }));
  const initial = await read();
  if (initial.scrollHeight > initial.height + 1) throw new Error('Long image should default to complete image');
  for (const name of ['适合宽度', '完整图片', '原始大小']) {
    if (await mode(name).count()) throw new Error(`Removed mode button still present: ${name}`);
  }
  const zoomBox = await dialog.locator('.gallery-zoom-controls').boundingBox();
  const navigationBox = await dialog.locator('.gallery-navigation').boundingBox();
  const viewportBox = await view.boundingBox();
  if (zoomBox.y < viewportBox.y + viewportBox.height || Math.abs(zoomBox.y - navigationBox.y) > 2 || navigationBox.x + navigationBox.width > zoomBox.x) throw new Error('Zoom controls should share footer row with navigation');
  await page.screenshot({ path: 'output/playwright/long-image-complete.png' });
  await view.locator('img').dblclick({ position: { x: 10, y: 60 } });
  if (await view.locator('img').evaluate(el => el.style.width) !== '1080px') throw new Error('Double click did not use original size');
  await view.evaluate(el => { el.scrollTop = 600; el.scrollLeft = 200; });
  const viewBox = await view.boundingBox();
  const pointer = { x: viewBox.x + 180, y: viewBox.y + 220 };
  const imagePoint = () => view.locator('img').evaluate((el, point) => {
    const r = el.getBoundingClientRect();
    return { x: (point.x - r.left) / r.width * el.naturalWidth, y: (point.y - r.top) / r.height * el.naturalHeight };
  }, pointer);
  await page.mouse.move(pointer.x, pointer.y);
  const beforePoint = await imagePoint();
  const beforeWheel = await read();
  await page.mouse.wheel(0, -100);
  await page.waitForFunction(width => document.querySelector('.gallery-viewport img').getBoundingClientRect().width > width + 5, beforeWheel.imageWidth);
  const afterPoint = await imagePoint();
  if (Math.abs(beforePoint.x - afterPoint.x) > 3 || Math.abs(beforePoint.y - afterPoint.y) > 3) throw new Error('Wheel zoom does not keep cursor position anchored');
  const wheelZoomed = await read();
  await page.mouse.wheel(0, 100);
  await page.waitForFunction(width => document.querySelector('.gallery-viewport img').getBoundingClientRect().width < width, wheelZoomed.imageWidth);
  const beforeSecondZoom = await read();
  await page.mouse.wheel(0, -100);
  await page.waitForFunction(width => document.querySelector('.gallery-viewport img').getBoundingClientRect().width > width + 5, beforeSecondZoom.imageWidth);
  const beforeDrag = await view.evaluate(el => ({ left: el.scrollLeft, top: el.scrollTop }));
  await page.mouse.down();
  await page.mouse.move(pointer.x - 60, pointer.y - 140, { steps: 8 });
  const dragged = await view.evaluate(el => ({ left: el.scrollLeft, top: el.scrollTop }));
  if (dragged.left < beforeDrag.left + 50 || dragged.top < beforeDrag.top + 130) throw new Error(`Drag did not pan in both directions: ${JSON.stringify({ beforeDrag, dragged })}`);
  await page.mouse.move(viewBox.x - 20, viewBox.y - 20, { steps: 4 });
  await page.mouse.up();
  const released = await read();
  await page.mouse.move(pointer.x, pointer.y);
  if ((await read()).top !== released.top || await view.evaluate(el => el.classList.contains('gallery-dragging'))) throw new Error('Dragging stuck after releasing outside viewer');
  await page.keyboard.press('0');
  const fit = await read();
  if (fit.scrollHeight > fit.height + 1 || fit.top !== 0) throw new Error('Fit mode overflows');
  await page.keyboard.press('+');
  const zoomed = await read();
  if (zoomed.imageWidth <= initial.imageWidth) throw new Error('Keyboard zoom failed');
  await page.keyboard.press('0');
  if ((await read()).top !== 0) throw new Error('Reset did not return to top');
  await view.locator('img').dblclick({ position: { x: 10, y: 60 } });
  await view.evaluate(el => { el.scrollTop = 600; });
  await page.keyboard.press('0');
  if ((await read()).top !== 0) throw new Error('Repeated reset did not return to top');
  await view.locator('img').dblclick({ position: { x: 10, y: 60 } });
  if (await view.locator('img').evaluate(el => el.style.width) !== '1080px') throw new Error('Double click did not use original size');
  await page.keyboard.press('0');
  await page.screenshot({ path: 'output/playwright/long-image-reading.png' });
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => document.querySelector('.gallery-viewport img')?.alt.endsWith('图片 2') && document.querySelector('.gallery-viewport')?.getAttribute('aria-busy') === 'false');
  const wide = await read();
  if (wide.scrollHeight > wide.height + 1) throw new Error('Normal image should default to fit');
  await mode('下一张图片').click();
  await dialog.getByRole('alert').waitFor();
  failed = false;
  await mode('重试').click();
  await page.waitForFunction(() => document.querySelector('.gallery-viewport')?.getAttribute('aria-busy') === 'false' && !document.querySelector('.gallery-error'));
  await mode('上一张图片').click(); await mode('上一张图片').click();
  await page.setViewportSize({ width: 600, height: 700 });
  await page.waitForFunction(() => document.querySelector('.gallery-viewport')?.clientHeight > 100);
  const compact = await dialog.boundingBox();
  if (compact.x < 0 || compact.y < 0 || compact.x + compact.width > 601 || compact.y + compact.height > 701) throw new Error('Dialog exceeds small window');
  await view.locator('img').dblclick({ position: { x: 10, y: 60 } });
  const compactView = await view.boundingBox();
  await page.mouse.move(compactView.x + 180, compactView.y + 180);
  const compactBefore = await view.evaluate(el => el.scrollTop);
  await page.mouse.down();
  await page.mouse.move(compactView.x + 140, compactView.y + 100, { steps: 6 });
  await page.mouse.up();
  if ((await read()).top < compactBefore + 75) throw new Error('Drag failed in scaled compact window');
  await page.keyboard.press('0');
  await page.screenshot({ path: 'output/playwright/long-image-compact.png' });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  return { defaultCompleteImage: true, modeButtonsRemoved: true, zoomInFooter: true, wheelZoom: true, cursorAnchoring: true, dragPan: true, releaseOutside: true, keyboardZoomAndReset: true, doubleClickOriginal: true, arrowNavigation: true, normalImageFit: true, retry: true, compactWindow: true, compactDrag: true, escapeClose: true };
}
