async page => {
  const preferences = { theme: 'light', zoom: 100, exit: 'close', shortcuts: true, animations: false, showSidebar: false };
  const states = { 'heybox.preferences': preferences, 'heybox.community-filter': { mode: 'all', included: [], excluded: [], unknown: true }, 'heybox.bookmarks': [], 'heybox.history': [] };
  const post = { id: 1, userId: '12345', author: '测试盒友', avatar: '测', avatarUrl: '', color: '#ddd', time: '刚刚', title: '快捷键测试', excerpt: '测试摘要', body: ['正文'], topicIds: [], topics: [], likes: 0, comments: 0, images: [], level: 0, medalUrl: '', medalName: '', liked: false, createdAt: 0, videoUrl: '', isCy: false };
  await page.addInitScript(saved => { for (const [key,value] of Object.entries(saved)) localStorage.setItem(key,JSON.stringify(value)); }, states);
  await page.route('**/api/command', async route => {
    const request = route.request().postDataJSON(); let data;
    switch(request.type) {
      case 'bootstrap': data={account:{id:'12345',name:'测试账号',avatarUrl:''},states,dataDirectory:'synthetic-test'}; break;
      case 'stateGet': data=states[request.payload.key]??null; break;
      case 'stateSet': states[request.payload.key]=request.payload.value; data=true; break;
      case 'communities': data=[]; break;
      case 'emojis': data={version:'synthetic',emojis:[]}; break;
      case 'feed': data={posts:[post],cursor:{offset:30,topics:{},exhausted:[],rotation:0},hasMore:false}; break;
      case 'detail': data={post,comments:[],page:1,hasMore:false,isCy:false}; break;
      default: throw new Error(`Unexpected command ${request.type}`);
    }
    await route.fulfill({json:{ok:true,data}});
  });
  const edit = async (action, keys) => { await page.getByRole('button',{name:`修改${action}快捷键`,exact:true}).click(); await page.keyboard.press(keys); };
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('heading',{name:post.title}).waitFor();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.locator('.settings-nav').getByRole('button',{name:'快捷键',exact:true}).click();
  await edit('搜索帖子','Control+g');
  await edit('返回','Control+g');
  await page.getByRole('alert').filter({hasText:'已用于“搜索帖子”'}).waitFor();
  await page.getByRole('button',{name:'取消录入',exact:true}).click();
  if (await page.getByRole('dialog').count()!==1) throw new Error('Escape recording cancellation closed settings');
  await edit('返回','Control+r');
  await page.getByRole('alert').filter({hasText:'请换一个'}).waitFor();
  await page.keyboard.press('Control+b');
  await edit('打开设置','Control+Shift+s');
  await edit('关闭弹窗','F9');
  await page.screenshot({path:'output/playwright/shortcuts.png'});
  await page.getByRole('button',{name:'完成',exact:true}).click();
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('heybox.preferences')).keybindings?.back?.code==='KeyB');
  await page.waitForResponse(response=>{try { const r=response.request().postDataJSON();return r?.type==='stateSet'&&r.payload?.key==='heybox.preferences'&&r.payload.value.keybindings?.close?.code==='F9'; } catch {return false} });
  await page.reload();
  await page.getByRole('heading',{name:post.title}).waitFor();
  await page.keyboard.press('Control+g');
  if (!(await page.getByRole('textbox',{name:'搜索帖子或社区'}).evaluate(el=>el===document.activeElement))) throw new Error('Saved search shortcut not applied');
  await page.getByRole('textbox',{name:'搜索帖子或社区'}).press('Control+Shift+s');
  if (await page.getByRole('dialog').count()) throw new Error('Shortcut triggered while editing');
  await page.locator('.post-content').click();
  await page.getByRole('button',{name:'返回',exact:true}).waitFor();
  await page.keyboard.press('Control+b');
  await page.locator('.post-content').waitFor();
  if (await page.locator('.post-detail').count()) throw new Error('Custom back failed');
  await page.keyboard.press('Control+Shift+s');
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('F9');
  if (await page.getByRole('dialog').count()) throw new Error('Custom close failed');
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.locator('.settings-nav').getByRole('button',{name:'快捷键',exact:true}).click();
  await page.getByRole('switch',{name:'启用快捷键',exact:true}).click();
  if (!(await page.getByRole('button',{name:'修改搜索帖子快捷键',exact:true}).isDisabled())) throw new Error('Disabled editor remains active');
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+Shift+s');
  if (await page.getByRole('dialog').count()) throw new Error('Disabled shortcut still active');
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.locator('.settings-nav').getByRole('button',{name:'快捷键',exact:true}).click();
  await page.getByRole('button',{name:'恢复默认快捷键'}).click();
  await page.getByRole('button',{name:'修改搜索帖子快捷键',exact:true}).filter({hasText:'Ctrl + K'}).waitFor();
  for (const action of ['返回','关闭弹窗']) {
    if (!(await page.getByRole('button',{name:`修改${action}快捷键`,exact:true}).textContent()).includes('Esc')) throw new Error('Navigation defaults are not both Escape');
  }
  await page.getByRole('switch',{name:'启用快捷键',exact:true}).click();
  await edit('返回','Escape');
  if (await page.getByRole('alert').count()) throw new Error('Escape shared binding rejected');
  await page.getByRole('button',{name:'完成',exact:true}).click();
  await page.locator('.post-content').click();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.keyboard.press('Escape');
  if (await page.getByRole('dialog').count() || await page.locator('.post-detail').count()!==1) throw new Error('Escape did not close overlay before returning');
  await page.keyboard.press('Escape');
  await page.locator('.post-content').waitFor();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.locator('.settings-nav').getByRole('button',{name:'快捷键',exact:true}).click();
  await edit('返回','Control+b');
  await edit('关闭弹窗','Control+b');
  if (await page.getByRole('alert').count()) throw new Error('Shared custom binding rejected');
  await page.getByRole('button',{name:'完成',exact:true}).click();
  const persisted = page.waitForResponse(response=>{try { const r=response.request().postDataJSON();return r?.type==='stateSet'&&r.payload?.key==='heybox.preferences'&&r.payload.value.keybindings?.close?.code==='KeyB'; } catch {return false} });
  await persisted;
  await page.reload();
  await page.locator('.post-content').click();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.keyboard.press('Control+b');
  if (await page.getByRole('dialog').count() || await page.locator('.post-detail').count()!==1) throw new Error('Shared custom key did not close overlay first');
  await page.keyboard.press('Control+b');
  await page.locator('.post-content').waitFor();
  return {legacyDefaults:true,duplicateConflict:true,reservedConflict:true,cancelRecording:true,persistence:true,allFourActions:true,inputSuppression:true,disableAndRestore:true,sharedEscapeDefaults:true,sharedCustomBinding:true,overlayPriority:true};
}
